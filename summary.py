"""
summary.py: a three-line plain-language summary of a result, in English and Hindi, for a proctor,
parent or cyber-cell officer who won't read the full report.

Built from templates, not generated by AI, so it can't invent anything and works offline:
  line 1  what TrustLens concluded
  line 2  the main reason
  line 3  what to do next
"""

from __future__ import annotations

MEDIA = {
    "image": ("image", "तस्वीर"),
    "video": ("video", "वीडियो"),
    "audio": ("voice note", "वॉइस नोट"),
}

TYPE_PHRASE = {
    "ai_generated": ("AI-generated", "AI से बनाई गई"),
    "face_swap_or_deepfake": ("a deepfake (face swap)", "डीपफेक (चेहरा बदला गया)"),
    "spliced_or_object_edited": ("edited: part of it was changed or pasted in", "एडिट की गई: इसका कुछ हिस्सा बदला या जोड़ा गया"),
    "document_or_text_edited": ("an edited document: text, dates or numbers were changed",
                                "एडिट किया गया दस्तावेज़: लिखावट, तारीख़ या अंक बदले गए"),
    "retouched": ("retouched or filtered", "रीटच या फ़िल्टर की गई"),
    "edited": ("edited", "एडिट की गई"),
}

# Known rule notes and test names, so the reason line can be in Hindi too.
REASON_HI = [
    ("Content Credentials", "फ़ाइल के अपने डिजिटल प्रमाण-पत्र (Content Credentials) बताते हैं कि यह AI से बनी है।"),
    ("metadata was written by an AI", "फ़ाइल की जानकारी (मेटाडेटा) किसी AI इमेज टूल ने लिखी है।"),
    ("embedded preview", "कैमरे ने फ़ाइल में जो छोटी प्रीव्यू तस्वीर रखी थी, वह इस तस्वीर से अलग है।"),
    ("changed after signing", "डिजिटल हस्ताक्षर के बाद फ़ाइल बदली गई है।"),
    ("copy-move", "तस्वीर का एक हिस्सा दूसरे हिस्से की कॉपी है।"),
    ("edited after capture", "मेटाडेटा के अनुसार फ़ाइल खींचने के बाद एडिट की गई।"),
    ("contradicts", "नोटिस की तारीख़ें VTOP के आधिकारिक रिकॉर्ड से मेल नहीं खातीं।"),
    ("VTOP", "नोटिस की तारीख़ें VTOP के आधिकारिक रिकॉर्ड से मेल नहीं खातीं।"),
    ("payment", "पेमेंट स्क्रीनशॉट की जानकारी असली ऐप के फ़ॉर्मैट से मेल नहीं खाती।"),
    ("transaction", "पेमेंट स्क्रीनशॉट की जानकारी असली ऐप के फ़ॉर्मैट से मेल नहीं खाती।"),
    ("earlier", "यही तस्वीर पहले इंटरनेट पर किसी और संदर्भ में छप चुकी है।"),
    ("AI tool", "फ़ाइल की जानकारी में किसी AI वीडियो/आवाज़ टूल का नाम दर्ज है।"),
]


def _reason(r: dict) -> tuple[str, str]:
    rev = r.get("reverse_search") or {}
    if rev.get("matches") and r.get("verdict") in ("no_evidence", "inconclusive"):
        m = rev["matches"][0]
        when = f" in {m['date'][:4]}" if (m.get("date") or "")[:4].isdigit() else ""
        return (f"This photo was already online{when} ({m.get('domain', 'another site')}): check that the story you "
                "received matches the original context.",
                f"यह तस्वीर पहले ही{(' ' + m['date'][:4] + ' में') if when else ''} इंटरनेट पर ({m.get('domain', 'दूसरी साइट')}) "
                "छप चुकी है: देखें कि आपको मिली कहानी असली संदर्भ से मेल खाती है या नहीं।")
    notes = r.get("rule_notes") or []
    if notes:
        en = notes[0]
        for key, hi in REASON_HI:
            if key.lower() in en.lower():
                return en, hi
        return en, f"मुख्य कारण (अंग्रेज़ी में): {en}"
    findings = [f for f in r.get("visual_findings") or [] if f.get("severity") in ("high", "medium")]
    if findings and r.get("verdict") not in ("no_evidence",):
        f = findings[0]
        where = f" ({f['location']})" if f.get("location") else ""
        en = f"Main sign: {f['finding']}{where}."
        return en, f"मुख्य संकेत (अंग्रेज़ी में): {f['finding']}{where}।"
    for s in r.get("forensic_signals") or []:
        if s.get("severity") in ("high", "medium") and s.get("points_to") != "none":
            return f"Main sign: {s['check']}.", f"मुख्य संकेत (अंग्रेज़ी में): {s['check']}।"
    if r.get("verdict") == "no_evidence":
        if r.get("llm_used"):
            return ("Neither the forensic tests nor the AI visual review found a sign of editing.",
                    "न फ़ॉरेंसिक जाँच और न AI जाँच को एडिटिंग का कोई संकेत मिला।")
        kind = r.get("media_kind", "image")
        if kind == "video":
            return ("The file and frame tests found nothing, but deepfakes and AI video rarely leave such traces.",
                    "फ़ाइल और फ़्रेम की जाँच में कुछ नहीं मिला, पर डीपफेक और AI वीडियो अक्सर ऐसे निशान नहीं छोड़ते।")
        if kind == "audio":
            return ("No AI tool is named in the file and no editing traces were found; a cloned voice leaves none.",
                    "फ़ाइल में किसी AI टूल का नाम या एडिटिंग का निशान नहीं मिला; नकली (क्लोन) आवाज़ ऐसा कोई निशान नहीं छोड़ती।")
        return ("Forensic tests found no technical traces, but most AI images and clean edits leave none.",
                "फ़ॉरेंसिक जाँच में कोई तकनीकी निशान नहीं मिला, पर ज़्यादातर AI तस्वीरें और साफ़ एडिट कोई निशान नहीं छोड़ते।")
    return ("No single piece of evidence settles it.", "कोई एक सबूत पक्का फ़ैसला नहीं देता।")


def build(r: dict) -> dict:
    media_en, media_hi = MEDIA.get(r.get("media_kind", "image"), MEDIA["image"])
    v = r.get("verdict")
    t_en, t_hi = TYPE_PHRASE.get(r.get("fake_type"), ("manipulated", "छेड़छाड़ की गई"))
    if v == "fake":
        l1 = (f"TrustLens found strong evidence that this {media_en} is {t_en}.",
              f"TrustLens को पक्के सबूत मिले कि यह {media_hi} {t_hi} है।")
    elif v == "likely_fake":
        l1 = (f"This {media_en} is likely {t_en}.", f"यह {media_hi} शायद {t_hi} है।")
    elif v == "inconclusive":
        l1 = ("TrustLens couldn't decide: some signs point to manipulation, but not enough to be sure.",
              "TrustLens पक्का नहीं कह सकता: कुछ संकेत छेड़छाड़ की ओर हैं, पर पूरे सबूत नहीं।")
    elif r.get("llm_used"):
        l1 = (f"TrustLens found no sign that this {media_en} was edited or made with AI. That isn't proof it's real.",
              f"TrustLens को इस {media_hi} में एडिटिंग या AI का कोई संकेत नहीं मिला। इसका मतलब यह नहीं कि यह पक्का असली है।")
    else:
        l1 = (f"This {media_en} wasn't fully checked: the AI review was off.",
              f"इस {media_hi} की पूरी जाँच नहीं हुई: AI जाँच बंद थी।")
    l2 = _reason(r)
    if v in ("fake", "likely_fake"):
        l3 = ("Don't forward it. Keep the evidence report (it records the file's fingerprint) and, if someone is "
              "being harmed or cheated, report it at cybercrime.gov.in or call 1930.",
              "इसे आगे न भेजें। सबूत की रिपोर्ट संभालकर रखें (उसमें फ़ाइल की पहचान दर्ज है)। अगर किसी को नुकसान "
              "या धोखा हो रहा है, तो cybercrime.gov.in पर शिकायत करें या 1930 पर कॉल करें।")
    elif v == "inconclusive":
        l3 = ("Ask the sender for the original file and check it again, or ask an expert before acting on it.",
              "भेजने वाले से असली फ़ाइल माँगें और दोबारा जाँचें, या कोई कदम उठाने से पहले किसी विशेषज्ञ से पूछें।")
    elif r.get("llm_used"):
        l3 = ("If it still seems wrong, ask the sender for the original file, or check the source it claims to come from.",
              "अगर फिर भी शक हो, तो भेजने वाले से असली फ़ाइल माँगें या जिस स्रोत का दावा है वहाँ जाँचें।")
    else:
        l3 = ("Turn on the AI review (add an API key) and open the file again before relying on this result.",
              "इस नतीजे पर भरोसा करने से पहले AI जाँच चालू करें (API key जोड़ें) और फ़ाइल दोबारा खोलें।")
    return {"en": [l1[0], l2[0], l3[0]], "hi": [l1[1], l2[1], l3[1]]}


def headline(r: dict) -> str:
    """Short verdict heading, naming the finding when its type is known (mirrors web/src/Verdict.tsx)."""
    v = r.get("verdict")
    if v == "no_evidence" and r.get("media_kind") == "audio":
        return "No traces found"
    if v == "no_evidence" and r.get("media_kind") == "video" and r.get("llm_used"):
        return "No signs found"
    if v == "no_evidence" and not r.get("llm_used"):
        return "Not enough evidence"
    if v == "inconclusive":
        return "Inconclusive"
    if v not in ("fake", "likely_fake"):
        return r.get("verdict_label", "")
    likely = "Likely " if v == "likely_fake" else ""
    t = r.get("fake_type")
    if t == "edited" and r.get("media_kind") == "audio":
        return "Likely edited" if likely else "Edited"
    if t == "ai_generated":
        return f"{likely}AI-generated"
    if t == "face_swap_or_deepfake":
        return f"{likely}deepfake" if likely else "Deepfake"
    return "Likely manipulated" if likely else "Manipulated"
