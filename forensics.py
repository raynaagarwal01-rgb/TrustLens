def _exif(img: Image.Image) -> dict:
    out = {}
    try:
        exif = img.getexif()
    except Exception:
        return out
    for tag, val in exif.items():
        out[ExifTags.TAGS.get(tag, str(tag))] = val
    try:
        for tag, val in exif.get_ifd(0x8769).items():  # Exif sub-IFD: DateTimeOriginal etc.
            out[ExifTags.TAGS.get(tag, str(tag))] = val
    except Exception:
        pass
    clean = {}
    for k, v in out.items():
        if isinstance(v, bytes):
            continue
        s = str(v).strip("\x00 ").strip()
        if s and len(s) < 300:
            clean[k] = s
    return clean


def _xmp(data: bytes) -> str:
    start = data.find(b"<x:xmpmeta")
    if start < 0:
        return ""
    end = data.find(b"</x:xmpmeta>", start)
    return data[start:end + 12 if end > 0 else start + 20000].decode("utf-8", "replace")


def _exif_time(s: str):
    try:
        return dt.datetime.strptime(s[:19], "%Y:%m:%d %H:%M:%S")
    except (ValueError, TypeError):
        return None


AI_SOURCE_TYPES = {
    "trainedAlgorithmicMedia": "generated by AI",
    "compositeWithTrainedAlgorithmicMedia": "edited or composited with AI",
    "algorithmicMedia": "generated by an algorithm",
    "compositeSynthetic": "a composite including synthetic elements",
}


def read_c2pa(data: bytes) -> dict | None:
    """Read what a Content Credentials (C2PA) manifest *says*, without a C2PA library.
    The manifest's claims are CBOR inside JUMBF boxes, so the key strings are readable bytes.
    TrustLens does not verify the cryptographic signature."""
    if b"c2pa" not in data or b"jumb" not in data:
        return None
    text = data.decode("latin-1")
    source_types = sorted(set(re.findall(r"digitalsourcetype/([A-Za-z]+)", text)))
    actions = []
    for m in re.finditer(r"description.{0,3}?([A-Z][\x20-\x7e]{6,120}?)(?=[^\x20-\x7e]|q?digitalSourceType|$)", text):
        a = m.group(1).strip().rstrip(".")
        if a not in actions and not a.startswith("http"):
            actions.append(a)
    gen = re.search(r"claim_generator(?:_info)?.{0,6}?name.{0,3}?([A-Za-z][\x20-\x7e]{2,80}?)(?=g?version|[^\x20-\x7e])", text)
    orgs = []
    for m in re.finditer(rb"\x55\x04\x0a[\x0c\x13]([\x01-\x7f])", data):  # X.509 organisationName
        org = data[m.end(): m.end() + m.group(1)[0]].decode("utf-8", "replace")
        if org not in orgs:
            orgs.append(org)
    ingredients = []
    for m in re.finditer(r"dc:title.{0,3}?([\x20-\x7e]{3,100}?)(?=[^\x20-\x7e])", text):
        t = re.sub(r'^[a-z]?"', "", m.group(1)).strip()
        if t and t not in ingredients:
            ingredients.append(t)
    return {
        "source_types": source_types,
        "ingredients": ingredients[:6],
        "actions": actions[:5],
        "generator": re.sub(r'^[a-z]?"', "", gen.group(1)).strip() if gen else "",
        "signed_by": orgs[:3],
        "watermark": "SynthID" if b"SynthID" in data else "",
    }


def verify_c2pa(data: bytes, fmt: str | None) -> dict:
    """Cryptographic check with the official C2PA library (pip install c2pa-python), when installed.
    validation_state: 'Trusted' (valid, signer on the trust list), 'Valid' (valid signature, signer not
    on the trust list) or 'Invalid' (e.g. the image changed after signing)."""
    try:
        import c2pa  # type: ignore
    except Exception:
        return {"status": "unavailable", "detail": "Install c2pa-python to verify signatures."}
    mime = {"JPEG": "image/jpeg", "PNG": "image/png", "WEBP": "image/webp", "TIFF": "image/tiff"}.get(fmt or "", "image/jpeg")
    try:
        with c2pa.Reader(mime, io.BytesIO(data)) as reader:
            store = json.loads(reader.json())
            state = reader.get_validation_state() or store.get("validation_state")
    except Exception as e:
        return {"status": "error", "detail": f"{type(e).__name__}: {str(e)[:160]}"}
    results = store.get("validation_results") or {}
    active = results.get("activeManifest") or {}
    failures = [f"{x.get('code')}: {x.get('explanation', '')}" for x in active.get("failure", [])]
    failures += [f"{x.get('code')}: {x.get('explanation', '')}" for x in store.get("validation_status", [])
                 if "fail" in str(x.get("code", "")).lower() or "mismatch" in str(x.get("code", "")).lower()]
    manifest = (store.get("manifests") or {}).get(store.get("active_manifest", ""), {})
    sig = manifest.get("signature_info") or {}
    return {"status": "ok", "state": state, "failures": failures[:6],
            "issuer": sig.get("issuer", ""), "signed_at": sig.get("time", ""),
            "title": manifest.get("title", ""),
            "ingredients": [i.get("title", "") for i in manifest.get("ingredients", [])][:6]}


def metadata(data: bytes, img: Image.Image) -> tuple[dict, list[dict]]:
    exif = _exif(img)
    text_chunks = {k: str(v)[:2000] for k, v in (img.info or {}).items()
                   if isinstance(v, (str, bytes)) and k not in ("icc_profile", "exif", "xmp")}
    text_chunks = {k: (v.decode("utf-8", "replace") if isinstance(v, bytes) else v) for k, v in text_chunks.items()}
    xmp = _xmp(data)
    c2pa_info = read_c2pa(data)
    c2pa = c2pa_info is not None
    signals = []

    # AI generator traces anywhere in the metadata
    haystack = " ".join([" ".join(f"{k}={v}" for k, v in exif.items()),
                         " ".join(f"{k}={v}" for k, v in text_chunks.items()), xmp])
    sd_params = any(k.lower() in ("parameters", "prompt", "workflow", "negative_prompt") for k in text_chunks) \
        and re.search(r"steps|sampler|seed|cfg|ksampler|negative", haystack, re.I)
    ai = AI_MARKERS.search(haystack)
    if sd_params or ai:
        what = "image-generator settings (prompt / sampler / seed)" if sd_params else f"'{ai.group(0)}'"
        signals.append(_signal("AI generator trace in metadata", "high",
                               f"The file's metadata contains {what}, which AI image generators write.", "ai"))
    if c2pa:
        c2pa_info["verification"] = verify_c2pa(data, img.format)
        ver = c2pa_info["verification"]
        if ver.get("status") == "ok" and (ver.get("state") == "Invalid" or ver.get("failures")):
            signals.append(_signal("Content Credentials fail verification", "high",
                                   "The official C2PA check reports: " + "; ".join(ver["failures"][:3] or ["invalid"])
                                   + ". The usual cause is the image being changed after it was signed.", "edited"))
        ai_types = [t for t in c2pa_info["source_types"] if t in AI_SOURCE_TYPES]
        who = ", ".join(c2pa_info["signed_by"]) or "an unknown signer"
        said = "; ".join(f"'{a}'" for a in c2pa_info["actions"][:3])
        if ai_types:
            meaning = AI_SOURCE_TYPES[ai_types[0]]
            signals.append(_signal("Content Credentials declare AI generation", "high",
                                   f"The file's Content Credentials, signed by {who}, state it was {meaning} "
                                   f"(digital source type: {', '.join(ai_types)})" + (f": {said}" if said else "")
                                   + (". They also record an invisible SynthID watermark"
                                      if c2pa_info["watermark"] and "SynthID" not in said else "")
                                   + (f". Signature check: {ver['state']}." if ver.get("status") == "ok" else
                                      ". TrustLens read the manifest but could not check its signature (install "
                                      "c2pa-python, or verify at contentcredentials.org/verify)."), "ai"))
        else:
            signals.append(_signal("Content Credentials (C2PA) present", "info",
                                   f"The file carries a provenance manifest signed by {who}"
                                   + (f" ({said})" if said else "") + ". Credentials describe where a file came "
                                   "from; they are not proof the content is true. Signature not verified by "
                                   "TrustLens; check at contentcredentials.org/verify.", "none"))

    software = exif.get("Software", "") + " " + exif.get("ProcessingSoftware", "")
    creator = re.search(r'CreatorTool(?:="|>)([^"<]+)', xmp)
    editor = EDITOR_MARKERS.search(software + " " + (creator.group(1) if creator else "") + " " +
                                   " ".join(text_chunks.values()))
    if editor:
        signals.append(_signal("Editing software recorded", "medium",
                               f"Saved with {editor.group(0)}. Editing isn't proof of deception, "
                               "but the image is not straight from a camera.", "edited"))
    if re.search(r"xmpMM:History|stEvt:action", xmp) and "saved" in xmp.lower():
        signals.append(_signal("Edit history in XMP", "medium",
                               "XMP metadata records save/edit actions.", "edited"))

    taken, modified = _exif_time(exif.get("DateTimeOriginal", "")), _exif_time(exif.get("DateTime", ""))
    if taken and modified and abs((modified - taken).total_seconds()) > 120:
        signals.append(_signal("Modified after capture", "medium",
                               f"Taken {taken:%d %b %Y %H:%M}, last modified {modified:%d %b %Y %H:%M}.", "edited"))

    if exif.get("Make") or exif.get("Model"):
        signals.append(_signal("Camera metadata present", "info",
                               f"Camera: {exif.get('Make', '')} {exif.get('Model', '')}".strip()
                               + (f", taken {taken:%d %b %Y %H:%M}" if taken else "") + ".", "none"))
    elif not sd_params and not ai and not c2pa:
        signals.append(_signal("No camera metadata", "info",
                               "Normal for screenshots and images sent through WhatsApp or social media, "
                               "which strip metadata. Origin can't be confirmed from metadata.", "none"))

    meta = {"exif": exif, "text_chunks": {k: v[:300] for k, v in text_chunks.items()},
            "xmp_present": bool(xmp), "c2pa_present": c2pa, "c2pa": c2pa_info}
    return meta, signals

